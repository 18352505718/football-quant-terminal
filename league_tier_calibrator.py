    @classmethod
    def get_team_tier(cls, team_name: str, league_name: str = "") -> float:
        """获取球队的绝对能力基线系数 (0.35 ~ 1.00)"""
        if not team_name:
            return 0.65

        # 1. 优先查俱乐部精确映射
        for t_key, factor in cls.TEAM_POWER_MAP.items():
            if t_key in team_name or team_name in t_key:
                return factor

        # 2. 其次匹配所属联赛
        for l_key, factor in cls.TIER_FACTORS.items():
            if l_key in league_name or l_key in team_name:
                return factor

        # 3. 兜底基准
        return 0.65

    @classmethod
    def calibrate_cross_competition_xg(
        cls, 
        home_team: str, 
        away_team: str, 
        home_raw_xg: float, 
        away_raw_xg: float, 
        competition: str = "欧冠",
        home_league: str = "",
        away_league: str = "",
        elasticity: float = 0.80
    ) -> tuple[float, float]:
        """
        跨联赛攻防 xG 预期校准。
        通过双方球队的绝对硬度比，对各自国内统计得到的 raw xG 进行平滑映射。
        :param elasticity: 战力弹性系数 (默认 0.80)
        :return: (calibrated_home_xg, calibrated_away_xg)
        """
        # 如果是同国内联赛比赛，无需跨级别修正
        if competition not in ["欧冠", "欧罗巴", "欧联", "欧联杯", "欧协联", "亚冠", "亚冠精英", "世俱杯"]:
            return home_raw_xg, away_raw_xg

        s_h = cls.get_team_tier(home_team, home_league)
        s_a = cls.get_team_tier(away_team, away_league)

        # 战力比值
        power_ratio_h = s_h / max(0.2, s_a)
        power_ratio_a = s_a / max(0.2, s_h)

        # 幂律平滑缩放
        # 主队相对客队硬度高，主队进球期望上浮，客队进球期望被压制
        scale_h = float(np.clip(power_ratio_h ** elasticity, 0.40, 2.50))
        scale_a = float(np.clip(power_ratio_a ** elasticity, 0.40, 2.50))

        calibrated_h_xg = max(0.15, home_raw_xg * scale_h)
        calibrated_a_xg = max(0.15, away_raw_xg * scale_a)

        return round(calibrated_h_xg, 3), round(calibrated_a_xg, 3)
